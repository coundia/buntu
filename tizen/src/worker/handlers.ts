/**
 * CND IPTV Tizen - the work the WebAssembly domain does for the app (PRD 38 § 2.3).
 *
 * The same handlers run in a Web Worker when the TV has one that works, and on the main thread
 * when it does not (a Tizen 6 TV cannot start a module worker, Chromium 76). `WorkerBridge` picks.
 */

import init, {
  wasm_get_schema_sql,
  wasm_is_adult_category,
  wasm_normalize_group_key,
  wasm_normalize_title,
  wasm_parse_m3u_chunk,
  wasm_parse_xmltv_chunk,
  wasm_parse_search_query,
  wasm_rank_search,
  wasm_score_recommendations,
  wasm_parse_saga_title,
  wasm_version,
  wasm_qr_matrix,
  wasm_pairing_create_offer,
  wasm_pairing_open,
  wasm_pairing_seal_reply,
} from '../wasm/pkg/cnd_domain_wasm.js';


// The file itself, as an URL next to the bundle (Vite copies it and rewrites this import).
import wasmUrl from '../wasm/pkg/cnd_domain_wasm_bg.wasm?url';

let ready: Promise<void> | null = null;
/** Where the WebAssembly comes from: its URL (the default, next to the bundle) or its bytes (tests). */
let wasmSource: string | URL | BufferSource | undefined;

export function setWasmSource(source: string | URL | BufferSource | undefined) {
  wasmSource = source;
  ready = null;
}

/**
 * The bytes of the WebAssembly file, read in one go. The loader generated by wasm-bindgen tries
 * `instantiateStreaming` first; on a TV (file served without the `application/wasm` type) that fails
 * after having read the response, and its fallback then fails with "body stream is locked". Handing
 * it the bytes avoids both. XHR is the last resort for engines whose `fetch` cannot read the app's files.
 */
async function loadWasmBytes(url: string): Promise<ArrayBuffer> {
  try {
    const response = await fetch(url);
    if (response.ok || response.status === 0) {
      const bytes = await response.arrayBuffer();
      if (bytes.byteLength > 0) return bytes;
    }
  } catch {
    /* try XHR below */
  }
  return new Promise<ArrayBuffer>((resolve, reject) => {
    const xhr = new XMLHttpRequest();
    xhr.open('GET', url, true);
    xhr.responseType = 'arraybuffer';
    xhr.onload = () => {
      const bytes = xhr.response as ArrayBuffer | null;
      if (bytes && bytes.byteLength > 0) resolve(bytes);
      else reject(new Error(`WebAssembly introuvable (${xhr.status})`));
    };
    xhr.onerror = () => reject(new Error('WebAssembly illisible'));
    xhr.send();
  });
}

export function ensureWasm(): Promise<void> {
  if (!ready) {
    ready = (async () => {
      const source = wasmSource ?? (await loadWasmBytes(String(wasmUrl)));
      await init({ module_or_path: source } as any);
      console.log('[Domain] cnd-domain-wasm initialized:', wasm_version());
    })();
    ready.catch(() => {
      ready = null; // let the next call try again
    });
  }
  return ready;
}

/** Runs one request. Throws on an unknown type or a failing call. */
export async function handleRequest(type: string, payload: any): Promise<any> {
  await ensureWasm();
  let result: any = null;

    switch (type) {
      case 'GET_VERSION':
        result = wasm_version();
        break;

      case 'GET_SCHEMA_SQL':
        result = wasm_get_schema_sql();
        break;

      case 'IS_ADULT_CATEGORY':
        result = wasm_is_adult_category(payload.group);
        break;

      case 'NORMALIZE_GROUP':
        result = wasm_normalize_group_key(payload.group);
        break;

      case 'NORMALIZE_TITLE':
        result = wasm_normalize_title(payload.raw, payload.group);
        break;

      case 'PARSE_M3U_CHUNK':
        result = wasm_parse_m3u_chunk(payload.content, payload.sourceUuid);
        break;

      case 'PARSE_XMLTV_CHUNK':
        result = wasm_parse_xmltv_chunk(payload.xmlContent, payload.cutoffTs);
        break;

      case 'PARSE_SEARCH_QUERY':
        result = wasm_parse_search_query(payload.query, payload.nowEpoch, payload.utcOffsetMinutes);
        break;

      case 'RANK_SEARCH':
        result = wasm_rank_search(JSON.stringify(payload.query), JSON.stringify(payload.candidates));
        break;

      case 'SCORE_RECOMMENDATIONS':
        result = wasm_score_recommendations(JSON.stringify(payload.taste), JSON.stringify(payload.items));
        break;

      case 'PARSE_SAGA_TITLE':
        result = wasm_parse_saga_title(payload.title, payload.year);
        break;

      case 'QR_MATRIX':
        result = wasm_qr_matrix(payload.text);
        break;

      // Pairing with a phone (PRD 39): the protocol is the Rust one, shared with Swift and Kotlin.
      case 'PAIRING_CREATE_OFFER':
        result = wasm_pairing_create_offer(
          payload.entropy, payload.tvName, payload.transport, payload.host, payload.port, payload.now
        );
        break;

      case 'PAIRING_OPEN':
        result = wasm_pairing_open(payload.state, payload.message, payload.now);
        break;

      case 'PAIRING_SEAL_REPLY':
        result = wasm_pairing_seal_reply(payload.replyKey, payload.session, payload.entropy, payload.result, payload.count);
        break;

      default:
        throw new Error(`Unknown worker message type: ${type}`);
    }


  return result;
}
